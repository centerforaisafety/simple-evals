# =============== PROMPTS ===============
SYSTEM_PROMPT = """The video you're seeing was generated by a simulator. Given how objects behave on earth, is the behaviour of the objects plausible? Your answer should be based on the events in the video and ignore the quality of the simulation. You should also ignore the framerate of the video, as it may be slowed down.

Your final choice should be boxed in the following format:
$\\boxed{Yes}$ or $\\boxed{No}$"""


def load_intphys2_data(dataset: str, max_samples: int = None):
    """Load IntPhys2 dataset from Hugging Face."""
    print(f"Loading IntPhys2 dataset from Hugging Face: {dataset}")

    hf_token = os.getenv('HF_TOKEN')
    if not hf_token:
        raise ValueError("HF_TOKEN not found in environment variables")

    dataset_obj = load_dataset(dataset, split="train", token=hf_token)
    examples = [dict(example) for example in dataset_obj] * 3

    # Limit samples if requested
    if max_samples:
        examples = examples[:max_samples]

    print(f"Loaded {len(dataset_obj)} unique examples (augmented to {len(examples)} total evaluations)")
    return examples


def format_message(example):
    """Format example into message format for the model."""
    base64_frames = example['frames_base64']

    # Build multimodal content with frames
    content = [{"type": "text", "text": "These are the frames from the video."}]

    for frame in base64_frames:
        content.append({
            "type": "image_url",
            "image_url": {
                "url": f'data:image/jpeg;base64,{frame}',
                "detail": "high"
            }
        })

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": content}
    ]
    return messages


# =============== ANSWER EXTRACTION ===============
def _last_boxed_content(text: str):
    """Return the content of the LAST ``\\boxed{...}`` in ``text`` using
    balanced-brace matching, or None if there is no ``\\boxed{``.

    The old regex ``r'\\boxed\{([^}]+)\}'`` stopped at the FIRST ``}``, so a
    nested wrapper like ``\\boxed{\\text{Yes}}`` captured only ``\\text{Yes``
    (which then failed the ``== "yes"`` check and dropped the item). Balancing
    braces here captures the full inner content (``\\text{Yes}``) so the answer
    token can be recovered downstream.
    """
    matches = list(re.finditer(r'\\boxed\s*\{', text, re.IGNORECASE))
    if not matches:
        return None
    open_brace = matches[-1].end() - 1  # index of the opening '{'
    depth = 0
    for j in range(open_brace, len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return text[open_brace + 1:j]
    return text[open_brace + 1:]  # unbalanced: take the remainder


def _extract_yes_no(text: str):
    """Pull the final standalone ``yes``/``no`` token out of a (possibly
    LaTeX-wrapped) string. Returns ``"yes"``/``"no"`` (lowercase) or None.

    Handles ``\\text{Yes}``, ``\\mathrm{No}``, ``\\textbf{Yes}``, ``\\boxed{}``,
    stray ``$``, surrounding whitespace and trailing punctuation. Only isolated
    ``yes``/``no`` tokens count, so ``no`` inside ``none``/``cannot`` and ``yes``
    inside a longer word are never grabbed.
    """
    if not isinstance(text, str):
        return None
    # Strip LaTeX command wrappers, keeping their braced argument content.
    cleaned = re.sub(
        r'\\(?:text|mathrm|textbf|mathbf|textit|mathit|boxed|rm|bf|it)\s*',
        '', text)
    # Drop braces / dollar signs / stray backslashes so only words remain.
    for ch in ('{', '}', '$', '\\'):
        cleaned = cleaned.replace(ch, ' ')
    # Take the LAST standalone yes/no token (not part of a longer word).
    tokens = re.findall(r'(?<![A-Za-z])(yes|no)(?![A-Za-z])', cleaned, re.IGNORECASE)
    if not tokens:
        return None
    return tokens[-1].lower()


def _extract_plausibility(text: str):
    """Map a ``plausible``/``implausible`` token to ``yes``/``no``.

    Models frequently box the semantic answer (``\\boxed{\\text{Plausible}}``)
    instead of the literal Yes/No the prompt asks for. ``plausible`` -> ``yes``
    (physics is normal), ``implausible`` -> ``no``. The alternation lists
    ``implausible`` FIRST and uses word boundaries so the ``plausible`` inside
    ``implausible`` is never mismatched. Returns ``"yes"``/``"no"`` or None.
    """
    if not isinstance(text, str):
        return None
    cleaned = re.sub(
        r'\\(?:text|mathrm|textbf|mathbf|textit|mathit|boxed|rm|bf|it)\s*',
        '', text)
    for ch in ('{', '}', '$', '\\'):
        cleaned = cleaned.replace(ch, ' ')
    tokens = re.findall(
        r'(?<![A-Za-z])(implausible|plausible)(?![A-Za-z])', cleaned, re.IGNORECASE)
    if not tokens:
        return None
    return 'no' if tokens[-1].lower() == 'implausible' else 'yes'


def parse_answer(response_text: str):
    """Parse the yes/no answer from a model response.

    Strategy (LaTeX-robust): pull the LAST ``\\boxed{...}`` block with balanced
    braces and look for a yes/no token inside it (handles ``\\boxed{\\text{Yes}}``).
    If the boxed block has no literal yes/no, also accept a
    ``plausible``/``implausible`` token inside it (``plausible`` -> yes,
    ``implausible`` -> no), so ``\\boxed{\\text{Plausible}}`` resolves correctly.

    The old whole-response prose fallback was REMOVED: scanning the entire
    response for the last standalone yes/no mis-extracted prose like
    ``\\boxed{\\text{Plausible}} because ... no collision`` -> "no" (a polarity
    flip). Parse-fails are now saved-on-failure and retryable, so dropping the
    fallback loses nothing but eliminates the flip.

    Returns ``{'extracted_answer': 'yes'|'no', 'prediction': 1|0}`` or None when
    there is genuinely no recoverable answer in the boxed block.
    """
    if not isinstance(response_text, str):
        return None

    boxed_content = _last_boxed_content(response_text)
    answer = None
    if boxed_content is not None:
        answer = _extract_yes_no(boxed_content)
        if answer is None:
            # Boxed but no literal yes/no -> accept plausible/implausible.
            answer = _extract_plausibility(boxed_content)

    if answer == "yes":
        return {'extracted_answer': 'yes', 'prediction': 1}
    elif answer == "no":
        return {'extracted_answer': 'no', 'prediction': 0}

    return None  # No yes/no answer found anywhere


# =============== JSONL I/O ===============
def read_jsonl_records(path: str) -> list:
    """Read per-item result records from a JSONL file.

    Skips blank lines and the trailing ``_type == 'metrics_summary'`` line.
    """
    records = []
    with open(path, 'r') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                continue
            if entry.get('_type') == 'metrics_summary':
                continue
            if 'example_idx' in entry:
                records.append(entry)
    return records


def compute_metrics(results, total):
    """Compute accuracy metrics.

    ``total`` is the full dataset size (denominator). Items that were parse-fails
    or missing count as incorrect (they are saved with is_correct=False / are
    simply absent from ``results``).
    """
    correct = sum(int(r['is_correct']) for r in results)

    # Group by plausibility over the results we actually have.
    plausible = [r for r in results if r['ground_truth'] == 1]
    implausible = [r for r in results if r['ground_truth'] == 0]

    plausible_correct = sum(int(r['is_correct']) for r in plausible)
    implausible_correct = sum(int(r['is_correct']) for r in implausible)

    # Items with a valid parsed answer (recoverable-vs-parsed diagnostics).
    parsed = [r for r in results if r.get('extracted_answer') is not None]

    return {
        'accuracy': round(100 * correct / total, 2) if total > 0 else 0,
        'correct': correct,
        'total': total,
        'parsed': len(parsed),
        'stored': len(results),
        'plausible_accuracy': round(100 * plausible_correct / len(plausible), 2) if plausible else 0,
        'plausible_correct': plausible_correct,
        'plausible_total': len(plausible),
        'implausible_accuracy': round(100 * implausible_correct / len(implausible), 2) if implausible else 0,
        'implausible_correct': implausible_correct,
        'implausible_total': len(implausible),
    }


async def get_model_prediction(agent, example, example_idx, max_attempts: int = 3):
    """Get the model prediction for a single video.

    ALWAYS returns a record (never None). The raw response is saved even when the
    answer cannot be parsed, so nothing is lost:
      * API/empty-content failure -> response=None, extracted_answer=None (retryable)
      * parse failure              -> response=<text>, extracted_answer=None (retryable + recoverable)
      * success                    -> response=<text>, extracted_answer='yes'/'no'
    """
    messages = format_message(example)

    # Retry only on API errors / empty content (not on parse failures).
    content = None
    for attempt in range(max_attempts):
        try:
            response = await agent.async_completions(messages=messages)
            content = response.content or response.reasoning_content
            assert content, "Model returned empty content and reasoning_content"
            break
        except Exception as e:
            if attempt == max_attempts - 1:
                print(f"{max_attempts} attempts failed for video {example_idx}: {e}")

    # Metadata common to every record (drop the heavy frames field).
    base = {k: v for k, v in example.items() if k != 'frames_base64'}
    base['example_idx'] = example_idx
    base['num_frames'] = len(example['frames_base64'])

    if content is None:
        # API failure: retryable on resume.
        return {
            **base,
            'response': None,
            'extracted_answer': None,
            'prediction': None,
            'is_correct': False,
        }

    parse_result = parse_answer(content)
    if parse_result is None:
        # Parse failure: SAVE the raw response so it is never lost. Marked
        # retryable (extracted_answer=None) so a redo=False rerun revisits it.
        return {
            **base,
            'response': content,
            'extracted_answer': None,
            'prediction': None,
            'is_correct': False,
        }

    is_correct = parse_result['prediction'] == example['ground_truth']
    return {
        **base,
        'response': content,
        'extracted_answer': parse_result['extracted_answer'],
        'prediction': parse_result['prediction'],
        'is_correct': is_correct,
    }


async def generate_predictions(agent,
                               dataset: str,
                               output_file: str,
                               max_concurrent: int = 10,
                               max_samples: int = None,
                               existing_results: list = None):
    """Generate model predictions for IntPhys2.

    Results are written incrementally to the JSONL ``output_file`` as they
    complete, so a killed job keeps everything done so far.
    """
    # Load IntPhys2 dataset
    examples = load_intphys2_data(dataset, max_samples=max_samples)
    total_examples = len(examples)

    # Attach a stable per-evaluation index (dataset load order is deterministic,
    # and the x3 augmentation makes 'id' non-unique, so example_idx is the key).
    indexed = list(enumerate(examples))

    # Resume: skip items that already have a valid parsed answer.
    existing_by_idx = {}
    if existing_results:
        for r in existing_results:
            existing_by_idx[r['example_idx']] = r
        good_idxs = {r['example_idx'] for r in existing_results
                     if r.get('extracted_answer') is not None}
        indexed = [(i, ex) for (i, ex) in indexed if i not in good_idxs]
        empty = len(existing_by_idx) - len(good_idxs)
        print(
            f"Skipping {len(good_idxs)} completed, rerunning {len(indexed)} "
            f"(empty/parse-fail: {empty}, missing: {len(indexed) - empty})"
        )

    if not indexed:
        print("No videos to process")

    # Create semaphore for concurrent processing
    semaphore = asyncio.Semaphore(max_concurrent)

    async def predict_with_semaphore(example, idx):
        async with semaphore:
            return await get_model_prediction(agent, example, idx)

    print(f"Generating predictions for {len(indexed)} videos...")
    tasks = [predict_with_semaphore(ex, i) for (i, ex) in indexed]

    # Open the JSONL file in append mode for incremental writes.
    output_path = Path(output_file)
    jsonl_file = open(output_path, 'a')
    write_lock = asyncio.Lock()

    correct = 0
    processed = 0
    pbar = tqdm(asyncio.as_completed(tasks), total=len(tasks), desc="Evaluating")
    for task in pbar:
        result = await task

        # Write EVERY result immediately (including parse-fails / API-fails).
        async with write_lock:
            jsonl_file.write(json.dumps(result) + '\n')
            jsonl_file.flush()

        processed += 1
        correct += int(result['is_correct'])
        accuracy = 100 * correct / processed if processed > 0 else 0.0
        cost = agent.all_token_usage.cost
        pbar.set_postfix({"acc": f"{accuracy:.1f}%", "cost": f"${cost:.3f}"})

    jsonl_file.close()

    # Read back the JSONL to build the authoritative merged result set
    # (dedupe by example_idx, last write wins so retried rows overwrite stale ones).
    merged_by_idx = {}
    for r in read_jsonl_records(output_file):
        merged_by_idx[r['example_idx']] = r
    all_results = list(merged_by_idx.values())

    return all_results, total_examples


def run_eval(model: str,
             output_file: str = None,
             dataset: str = "justinphan3110/intphys2",
             models_config: str = "configs/models.yaml",
             max_concurrent: int = 10,
             max_samples: int = None,
             redo: bool = True):
    """
    Run IntPhys2 evaluation.

    Args:
        model: Model name from models.yaml
        output_file: Path to output JSONL file (required)
        dataset: HuggingFace dataset identifier
        models_config: Path to models configuration file
        max_concurrent: Maximum number of concurrent API calls
        max_samples: If set, limit evaluation to first N samples
        redo: If True (default), rerun all. If False, resume: skip items with a
              valid parsed answer and only rerun missing/null-answer items.
    """
    output_path = Path(output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Load existing results from JSONL for resume (redo=False).
    existing_results = None
    if redo:
        # Fresh run: start from an empty JSONL so we don't append to stale rows.
        if output_path.exists():
            output_path.unlink()
    else:
        if output_path.exists():
            existing_results = read_jsonl_records(str(output_path))
            print(f"Loading existing results from {output_path}: {len(existing_results)} entries")

            # GUARD (data-destruction landmine): a NON-empty file that parses to
            # ZERO records is malformed (e.g. a pretty-printed JSON array, not
            # JSONL). Do NOT truncate + fully rerun it — that silently wipes real
            # data. Back it up and abort so a human can recover/convert it.
            if output_path.stat().st_size > 0 and len(existing_results) == 0:
                corrupt_bak = output_path.with_suffix(output_path.suffix + '.corrupt.bak')
                shutil.copy2(output_path, corrupt_bak)
                raise RuntimeError(
                    f"{output_path} is non-empty ({output_path.stat().st_size} bytes) but "
                    f"read_jsonl_records parsed 0 records — refusing to overwrite/rerun. "
                    f"Backed up to {corrupt_bak}. Inspect/convert it before resuming."
                )

            # Rewrite the JSONL RETAINING every row (dedupe by example_idx, last
            # write wins). Incomplete rows (null answer, but saved response) are
            # kept on disk so a crash mid-resume never loses their saved data;
            # the read-back merge dedupes retried rows over these stale ones.
            merged_by_idx = {}
            for r in existing_results:
                merged_by_idx[r['example_idx']] = r
            with open(output_path, 'w') as f:
                for r in merged_by_idx.values():
                    f.write(json.dumps(r) + '\n')
            good = sum(1 for r in merged_by_idx.values() if r.get('extracted_answer') is not None)
            print(f"Rewrote {output_path} with {len(merged_by_idx)} rows "
                  f"({good} complete, {len(merged_by_idx) - good} incomplete/retryable) for resume")

    model_agent = get_llm_agent_class(**get_agent_config(model, models_config))

    # Generate predictions (results are written incrementally to JSONL).
    results, total_examples = asyncio.run(
        generate_predictions(
            agent=model_agent,
            dataset=dataset,
            output_file=str(output_path),
            max_concurrent=max_concurrent,
            max_samples=max_samples,
            existing_results=existing_results,
        )
    )

    # Compute metrics (denominator = full dataset; parse-fails/missing = incorrect).
    metrics = compute_metrics(results, total_examples)

    print("\n=== IntPhys2 Results ===")
    print(f"Dataset: {dataset}")
    print(f"Overall Accuracy: {metrics['accuracy']}% ({metrics['correct']}/{metrics['total']})")
    print(f"Stored records: {metrics['stored']} | Parsed answers: {metrics['parsed']} | Total dataset: {metrics['total']}")
    print(f"Plausible videos: {metrics['plausible_accuracy']}% ({metrics['plausible_correct']}/{metrics['plausible_total']})")
    print(f"Implausible videos: {metrics['implausible_accuracy']}% ({metrics['implausible_correct']}/{metrics['implausible_total']})")

    print("\n===== Token Usage =====")
    print(f"Model: {model_agent.all_token_usage} | Max: {model_agent.max_token_usage}")

    # Append a metrics summary line to the JSONL (authoritative dashboard number).
    metrics_line = {
        '_type': 'metrics_summary',
        'model': model,
        'dataset': dataset,
        'metrics': metrics,
    }
    with open(output_path, 'a') as f:
        f.write(json.dumps(metrics_line) + '\n')

    print(f"\nResults saved to {output_path} (JSONL format, {len(results)} result lines + metrics summary)")


if __name__ == '__main__':
    fire.Fire(run_eval)
